import puppeteer from 'puppeteer';
import fs from 'fs';
const BASE = 'http://127.0.0.1:8901';
const credTxt = fs.readFileSync(process.env.HOME + '/workspace/app-tambang-emas/credentials-awal.txt', 'utf8');
const cred = {};
for (const line of credTxt.split('\n')) { const m = line.trim().match(/^(\w+)\s+\/\s+(\S+)/); if (m) cred[m[1]] = m[2]; }
const results = [];
const check = (n, ok, d='') => { results.push(ok); console.log((ok?'PASS':'FAIL')+' | '+n+' | '+d); };
const sleep = ms => new Promise(r=>setTimeout(r,ms));
const browser = await puppeteer.launch({headless:true, args:['--no-sandbox','--disable-dev-shm-usage']});
const page = await browser.newPage();
const errors = [];
page.on('pageerror', e => errors.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error' && !/Manifest|MIME type|401 \(Unauthorized\)/.test(m.text())) errors.push('console: ' + m.text()); });
await page.setViewport({width:390, height:844, isMobile:true, hasTouch:true});
await page.goto(BASE + '/', {waitUntil:'networkidle2', timeout:60000});
await sleep(1200);
let snap = await page.evaluate(() => ({txt: document.body.innerText, hasUser: !!document.getElementById('lg-user')}));
let txt = snap.txt;
check('UI: Layar login tampil', txt.includes('Pencatatan Hasil Tambang Emas') && snap.hasUser, '');
await page.screenshot({path:'/tmp/inputin-login.png'});
await page.type('#lg-user', 'staff1'); await page.type('#lg-pass', cred['staff1']);
await page.click('.login-card .btn'); await sleep(2500);
txt = await page.evaluate(() => document.body.innerText);
check('UI: Setelah login staff, form Input tampil dengan Shift 1/2', txt.includes('Input Hasil') && txt.includes('Shift 1') && txt.includes('Shift 2'), txt.slice(0,120).replace(/\n/g,' '));
check('UI: Ringkasan menampilkan Pendapatan Usaha', txt.includes('Pendapatan Usaha'), '');
await page.evaluate(() => { const h=document.getElementById('f-hasil'); h.value='100'; h.dispatchEvent(new Event('input',{bubbles:true})); });
await sleep(500);
txt = await page.evaluate(() => document.body.innerText);
check('UI: Ketik 100 -> ringkasan Operator 6,000 gr dan sisa 90,000 gr', txt.includes('6,000') && txt.includes('90,000'), '');
await page.screenshot({path:'/tmp/inputin-input.png'});
await page.evaluate(() => { [...document.querySelectorAll('.bottomnav button')].find(b=>b.textContent.includes('Laporan')).click(); });
await sleep(2000);
txt = await page.evaluate(() => document.body.innerText);
check('UI: Halaman Laporan termuat dengan KPI', txt.toUpperCase().includes('TOTAL HASIL') && txt.toUpperCase().includes('RATA-RATA PER HARI') && txt.includes('Total Per Kelompok'), '');
await page.evaluate(() => { [...document.querySelectorAll('.bottomnav button')].find(b=>b.textContent.includes('Riwayat')).click(); });
await sleep(2000);
txt = await page.evaluate(() => document.body.innerText);
check('UI: Halaman Riwayat termuat', txt.includes('Riwayat Transaksi'), '');
check('UI: Tidak ada error JavaScript', errors.length===0, errors.join(' | ').slice(0,300));
console.log('\nUI LIVE: ' + results.filter(Boolean).length + '/' + results.length + ' PASS');
await browser.close();
